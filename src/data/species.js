/**
 * species.js — Das Herz der Sammlung: alle Haustierarten.
 *
 * Jeder Eintrag beschreibt *eine Entwicklungsstufe*. Eine Entwicklungslinie
 * entsteht dadurch, dass Einträge über `entwicklung` aufeinander zeigen.
 * Verzweigungen sind ausdrücklich erwünscht: die erste Bedingung, die erfüllt
 * ist, gewinnt — deshalb stehen speziellere Zweige immer zuerst.
 *
 * Felder eines Eintrags
 * ---------------------
 *   id           eindeutiger Schlüssel
 *   name         Anzeigename
 *   element      siehe elements.js
 *   rarity       siehe rarity.js — bestimmt auch die Kunst-Stufe
 *   stufe        1 … 3, 4 = Megaform
 *   linie        gemeinsame Kennung aller Stufen einer Linie
 *   basis        Grundwerte (siehe S())
 *   form         Bauteile für den prozeduralen Zeichner (siehe render/petSprite.js)
 *   palette      [Hauptfarbe, Akzent, Schatten]
 *   text         kurze Beschreibung fürs Haustierbuch
 *   geschichte   Hintergrundgeschichte
 *   entwicklung  Liste möglicher Entwicklungen mit Bedingungen
 *   quellen      wo die Art vorkommt: 'start' | 'ei' | 'expedition' | 'ereignis'
 *   saison       nur in dieser Jahreszeit erhältlich
 *   geheim       im Buch erst nach dem Fund lesbar, nie zufällig aus Eiern
 *
 * Bedingungen einer Entwicklung
 * -----------------------------
 *   minLevel, minZuneigung, minGlueck, minVertrauen, minStimmung,
 *   minPflegeTage, minAttribut {staerke|intelligenz|tempo},
 *   item, tageszeit, persoenlichkeit [ids], minAktion {aktion: anzahl}
 */

