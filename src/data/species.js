const BY_ID = new Map(SPECIES.map((entry) => [entry.id, entry]));

/** Art per ID. */
export function species(id) {
  return BY_ID.get(id) || null;
}

/** Alle Arten (unveränderliche Sicht). */
export function allSpecies() {
  return SPECIES;
}

/** Anzahl aller Arten — die Zielmarke fürs Haustierbuch. */
export function speciesCount() {
  return SPECIES.length;
}

/** Alle Arten einer Entwicklungslinie, nach Stufe sortiert. */
export function lineSpecies(lineId) {
  return SPECIES.filter((entry) => entry.linie === lineId).sort((a, b) => a.stufe - b.stufe);
}

/** Die drei Starter. */
export function starterSpecies() {
  return SPECIES.filter((entry) => entry.starter);
}

/** Arten, die aus einer bestimmten Quelle stammen können. */
export function speciesFromSource(source) {
  return SPECIES.filter((entry) => entry.quellen?.includes(source));
}

/** Arten einer Seltenheit, optional auf eine Quelle eingeschränkt. */
export function speciesByRarity(rarityId, source = null) {
  return SPECIES.filter(
    (entry) => entry.rarity === rarityId && (!source || entry.quellen?.includes(source))
  );
}

/** Basisstufen einer Linie (Stufe 1) — daraus schlüpfen Eier. */
export function baseStageSpecies(source = 'ei') {
  return SPECIES.filter(
    (entry) => entry.stufe === 1 && !entry.geheim && entry.quellen?.includes(source)
  );
}

/** Die Vorstufe einer Art, falls es eine gibt. */
export function previousStage(id) {
  return SPECIES.find((entry) => entry.entwicklung?.some((step) => step.zu === id)) || null;
}

/** Vollständige Kette einer Linie als Liste von Listen (Verzweigungen bleiben sichtbar). */
export function evolutionTree(lineId) {
  const members = lineSpecies(lineId);
  const roots = members.filter((entry) => !previousStage(entry.id));
  const build = (entry) => ({
    art: entry,
    weiter: (entry.entwicklung || []).map((step) => species(step.zu)).filter(Boolean).map(build),
  });
  return roots.map(build);
}
